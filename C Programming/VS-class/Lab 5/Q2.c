#include <stdio.h>

int main() {
    printf("Size of Integer Data Type :-- %d bytes\n", sizeof(int));
    printf("Size of Float Data Type :-- %d bytes\n", sizeof(float));
    printf("Size of Double Data Type :-- %d bytes\n", sizeof(double));
    printf("Size of Character Data Type :-- %d bytes\n", sizeof(char));
    printf("Size of Long Integer Data Type :-- %d bytes\n", sizeof(long int));
    printf("Size of Short Integer Data Type :-- %d bytes\n", sizeof(short int));
    return 0;
}